CREATE TABLE application_reference_sequences (
  year INTEGER PRIMARY KEY,
  last_number INTEGER NOT NULL DEFAULT 0 CHECK (last_number >= 0),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE admins (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name VARCHAR(100) NOT NULL,
  last_name VARCHAR(100) NOT NULL,
  email VARCHAR(160) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(20) NOT NULL DEFAULT 'reviewer' CHECK (role IN ('admin', 'reviewer')),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uq_admins_email ON admins (LOWER(email));

CREATE TABLE candidates (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_reference VARCHAR(20) NOT NULL UNIQUE,
  first_name VARCHAR(100) NOT NULL,
  last_name VARCHAR(100) NOT NULL,
  email VARCHAR(160) NOT NULL,
  phone VARCHAR(60) NOT NULL,
  country VARCHAR(100) NOT NULL,
  city VARCHAR(100) NOT NULL,
  domain VARCHAR(120) NOT NULL,
  experience_level VARCHAR(80) NOT NULL,
  education_level VARCHAR(120) NOT NULL,
  current_status VARCHAR(120) NOT NULL,
  years_experience NUMERIC(4,1) NOT NULL DEFAULT 0 CHECK (years_experience >= 0),
  motivation TEXT NOT NULL,
  learning_goal TEXT NOT NULL,
  preferred_domain VARCHAR(120) NOT NULL,
  weekly_availability INTEGER NOT NULL DEFAULT 0 CHECK (weekly_availability >= 0),
  program_available BOOLEAN NOT NULL DEFAULT FALSE,
  status VARCHAR(30) NOT NULL DEFAULT 'new' CHECK (status IN ('new', 'to_review', 'in_evaluation', 'shortlisted', 'interview', 'selected', 'rejected')),
  automatic_score NUMERIC(5,2) CHECK (automatic_score BETWEEN 0 AND 100),
  human_score NUMERIC(5,2) CHECK (human_score BETWEEN 0 AND 100),
  final_score NUMERIC(5,2) CHECK (final_score BETWEEN 0 AND 100),
  qualification VARCHAR(30) CHECK (qualification IN ('priority', 'good_profile', 'to_review', 'low_match', 'low_priority')),
  submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_candidates_email ON candidates (email);
CREATE INDEX idx_candidates_status ON candidates (status);
CREATE INDEX idx_candidates_domain ON candidates (domain);
CREATE INDEX idx_candidates_automatic_score ON candidates (automatic_score);
CREATE INDEX idx_candidates_final_score ON candidates (final_score);
CREATE INDEX idx_candidates_submitted_at ON candidates (submitted_at);

CREATE TABLE candidate_skills (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  candidate_id INTEGER NOT NULL REFERENCES candidates(id) ON DELETE CASCADE,
  skill_name VARCHAR(120) NOT NULL,
  proficiency_level VARCHAR(20) NOT NULL CHECK (proficiency_level IN ('beginner', 'intermediate', 'advanced')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_candidate_skills_candidate_id ON candidate_skills (candidate_id);

CREATE TABLE projects (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  candidate_id INTEGER NOT NULL UNIQUE REFERENCES candidates(id) ON DELETE CASCADE,
  name VARCHAR(160) NOT NULL,
  description TEXT NOT NULL,
  problem_solved TEXT NOT NULL,
  candidate_role TEXT NOT NULL,
  personal_contribution TEXT NOT NULL,
  technologies VARCHAR(500) NOT NULL,
  github_url VARCHAR(500),
  gitlab_url VARCHAR(500),
  portfolio_url VARCHAR(500),
  demo_url VARCHAR(500),
  used_ai BOOLEAN NOT NULL DEFAULT FALSE,
  ai_usage_description TEXT,
  personal_contribution_with_ai TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE scoring_criteria (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  criterion_key VARCHAR(80) NOT NULL UNIQUE,
  criterion_name VARCHAR(160) NOT NULL,
  weight NUMERIC(5,2) NOT NULL CHECK (weight BETWEEN 0 AND 100),
  max_score NUMERIC(5,2) NOT NULL CHECK (max_score BETWEEN 0 AND 100),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE candidate_score_details (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  candidate_id INTEGER NOT NULL REFERENCES candidates(id) ON DELETE CASCADE,
  criterion_key VARCHAR(80) NOT NULL,
  raw_score NUMERIC(5,2) NOT NULL,
  weighted_score NUMERIC(5,2) NOT NULL,
  max_score NUMERIC(5,2) NOT NULL,
  explanation TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_candidate_score_details_candidate_id ON candidate_score_details (candidate_id);

CREATE TABLE evaluations (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  candidate_id INTEGER NOT NULL REFERENCES candidates(id) ON DELETE CASCADE,
  admin_id INTEGER NOT NULL REFERENCES admins(id) ON DELETE RESTRICT,
  technical_skills SMALLINT NOT NULL CHECK (technical_skills BETWEEN 0 AND 10),
  problem_solving SMALLINT NOT NULL CHECK (problem_solving BETWEEN 0 AND 10),
  project_quality SMALLINT NOT NULL CHECK (project_quality BETWEEN 0 AND 10),
  motivation SMALLINT NOT NULL CHECK (motivation BETWEEN 0 AND 10),
  learning_potential SMALLINT NOT NULL CHECK (learning_potential BETWEEN 0 AND 10),
  overall_score NUMERIC(5,2) NOT NULL CHECK (overall_score BETWEEN 0 AND 100),
  comment TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_evaluations_candidate_id ON evaluations (candidate_id);
CREATE INDEX idx_evaluations_admin_id ON evaluations (admin_id);

CREATE TABLE candidate_history (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  candidate_id INTEGER NOT NULL REFERENCES candidates(id) ON DELETE CASCADE,
  admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  action_type VARCHAR(40) NOT NULL CHECK (action_type IN ('APPLICATION_RECEIVED', 'AUTO_SCORE_CALCULATED', 'EVALUATION_ADDED', 'SCORE_UPDATED', 'STATUS_CHANGED')),
  old_value VARCHAR(255),
  new_value VARCHAR(255),
  description TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_candidate_history_candidate_id ON candidate_history (candidate_id);
CREATE INDEX idx_candidate_history_admin_id ON candidate_history (admin_id);

CREATE FUNCTION touch_updated_at() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$;

DO $$
DECLARE table_name TEXT;
BEGIN
  FOREACH table_name IN ARRAY ARRAY['application_reference_sequences', 'admins', 'candidates', 'projects', 'scoring_criteria', 'evaluations'] LOOP
    EXECUTE format('CREATE TRIGGER touch_updated_at BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION touch_updated_at()', table_name);
  END LOOP;
END;
$$;
